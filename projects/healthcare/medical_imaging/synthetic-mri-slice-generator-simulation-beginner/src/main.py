#!/usr/bin/env python3
"""Synthetic MRI Slice Generator: Simulation (Logistic Growth): a logistic-growth simulation for Synthetic MRI Slice Generator.

Synthetic MRI slices are built from geometric phantoms, such as a head model made of overlapping ellipses, each assigned a tissue-like intensity. This mirrors how real scanners translate proton density and relaxation properties into grayscale values. Seeded generation gives developers a ground truth for testing segmentation and detection code with no patient data involved.
Data idea: Generates seeded ellipse-phantom slices at configurable resolution and saves the matching tissue-label masks as ground truth.

Integrates dP/dt = r*P*(1 - P/K) with explicit Euler steps, modeling how a
Synthetic MRI Slice Generator quantity grows toward its carrying capacity, and prints the
trajectory table plus summary statistics.
"""

import argparse
import random

PARAMS = {'slice_size': 'pixel dimensions of each generated slice', 'phantom_count': 'number of ellipse phantoms per slice', 'seed': 'random seed for reproducible phantoms', 'intensity_noise': 'noise added to tissue intensities'}


def _num(value, fallback):
    """Coerce a descriptive-text PARAMS value to a number, else fallback."""
    try:
        return int(value)
    except (TypeError, ValueError):
        try:
            return float(value)
        except (TypeError, ValueError):
            return fallback


def simulate(params, steps, dt):
    """Euler-integrate logistic growth; return [(t, value)] rows."""
    r = _num(params.get("r"), 0.4)
    K = _num(params.get("K"), 1000.0)
    value = _num(params.get("P0"), 50.0)
    rows = [(0.0, round(value, 3))]
    t = 0.0
    for _ in range(steps):
        value += dt * r * value * (1.0 - value / K)
        t += dt
        rows.append((round(t, 4), round(value, 3)))
    return rows


def print_trajectory(rows, every):
    """Print every Nth trajectory row plus the final state."""
    print("Synthetic MRI Slice Generator logistic-growth trajectory")
    print("{:>10} {:>14}".format("t", "value"))
    print("-" * 26)
    for t, value in rows[::every]:
        print("{:>10} {:>14}".format(t, value))
    if rows[-1] != rows[::every][-1]:
        t, value = rows[-1]
        print("  ...")
        print("{:>10} {:>14}".format(t, value))


def main():
    parser = argparse.ArgumentParser(
        description="Synthetic MRI Slice Generator: Simulation (Logistic Growth): simulate Synthetic MRI Slice Generator growth.")
    parser.add_argument("--seed", type=int, default=42,
                        help="random seed (default 42)")
    parser.add_argument("--steps", type=int,
                        default=_num(PARAMS.get("steps"), 40),
                        help="Euler integration steps")
    parser.add_argument("--dt", type=float, default=_num(PARAMS.get("dt"), 0.1),
                        help="time step size")
    args = parser.parse_args()
    random.seed(args.seed)

    rows = simulate(PARAMS, args.steps, args.dt)
    print_trajectory(rows, every=max(1, len(rows) // 10))
    values = [v for _, v in rows]
    print("-" * 26)
    print("steps: {}  dt: {}".format(args.steps, args.dt))
    print("start: {:.3f}  end: {:.3f}  peak: {:.3f}".format(
        values[0], values[-1], max(values)))
    print("carrying capacity K: {}".format(PARAMS.get("K", 1000.0)))


if __name__ == "__main__":
    main()
