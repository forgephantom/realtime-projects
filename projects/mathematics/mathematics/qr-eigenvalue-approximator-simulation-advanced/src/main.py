#!/usr/bin/env python3
"""QR Algorithm Eigenvalue Approximator: Simulation (Logistic Growth): a logistic-growth simulation for QR Algorithm Eigenvalue Approximator.

The QR algorithm repeatedly factors a matrix into orthogonal Q times upper-triangular R and multiplies them back in reverse order; the iterates converge to reveal the eigenvalues on the diagonal. It is the standard dense eigensolver in numerical libraries. This educational version runs it on small symmetric matrices with shift acceleration.
Data idea: The demo builds random symmetric matrices with a seeded RNG and compares converged diagonal entries against characteristic-polynomial roots.

Integrates dP/dt = r*P*(1 - P/K) with explicit Euler steps, modeling how a
QR Algorithm Eigenvalue Approximator quantity grows toward its carrying capacity, and prints the
trajectory table plus summary statistics.
"""

import argparse
import random

PARAMS = {'iterations': 'max QR steps', 'shift': 'whether to use Wilkinson-style shifts', 'size': 'matrix dimension'}


def _num(value, fallback):
    """Coerce a descriptive-text PARAMS value to a number, else fallback."""
    try:
        return int(value)
    except (TypeError, ValueError):
        try:
            return float(value)
        except (TypeError, ValueError):
            return fallback


def simulate(params, steps, dt):
    """Euler-integrate logistic growth; return [(t, value)] rows."""
    r = _num(params.get("r"), 0.4)
    K = _num(params.get("K"), 1000.0)
    value = _num(params.get("P0"), 50.0)
    rows = [(0.0, round(value, 3))]
    t = 0.0
    for _ in range(steps):
        value += dt * r * value * (1.0 - value / K)
        t += dt
        rows.append((round(t, 4), round(value, 3)))
    return rows


def print_trajectory(rows, every):
    """Print every Nth trajectory row plus the final state."""
    print("QR Algorithm Eigenvalue Approximator logistic-growth trajectory")
    print("{:>10} {:>14}".format("t", "value"))
    print("-" * 26)
    for t, value in rows[::every]:
        print("{:>10} {:>14}".format(t, value))
    if rows[-1] != rows[::every][-1]:
        t, value = rows[-1]
        print("  ...")
        print("{:>10} {:>14}".format(t, value))


def main():
    parser = argparse.ArgumentParser(
        description="QR Algorithm Eigenvalue Approximator: Simulation (Logistic Growth): simulate QR Algorithm Eigenvalue Approximator growth.")
    parser.add_argument("--seed", type=int, default=42,
                        help="random seed (default 42)")
    parser.add_argument("--steps", type=int,
                        default=_num(PARAMS.get("steps"), 40),
                        help="Euler integration steps")
    parser.add_argument("--dt", type=float, default=_num(PARAMS.get("dt"), 0.1),
                        help="time step size")
    args = parser.parse_args()
    random.seed(args.seed)

    rows = simulate(PARAMS, args.steps, args.dt)
    print_trajectory(rows, every=max(1, len(rows) // 10))
    values = [v for _, v in rows]
    print("-" * 26)
    print("steps: {}  dt: {}".format(args.steps, args.dt))
    print("start: {:.3f}  end: {:.3f}  peak: {:.3f}".format(
        values[0], values[-1], max(values)))
    print("carrying capacity K: {}".format(PARAMS.get("K", 1000.0)))


if __name__ == "__main__":
    main()
